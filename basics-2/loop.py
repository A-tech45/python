l1 = ["apple" , "mango" , "banana"]
for frut in l1 :
    print(frut , end="-")  # end is used to add things in the end

print(len(l1)) # len() is used to get the length of an item

for i in range(len(l1)):  #range is the function where u can add a starting point and an ending point
    print(l1[i])

  
    

        